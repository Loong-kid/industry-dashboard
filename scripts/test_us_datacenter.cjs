const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const c = vm.createContext({});
vm.runInContext(fs.readFileSync('assets/us-datacenter.js','utf8'),c);
const doc = {series:{AWS:[['2026-09-30',100]],Google:[['2026-09-30',-10]],Unavailable:[['2026-09-30',null]]},default_series:['AWS','Google']};
const select = saved => Array.from(c.dcComparisonDefaults(doc,saved));
assert.deepEqual(select(undefined),['AWS','Google']);
assert.deepEqual(select(['AWS','Unavailable']),['AWS']);
assert.deepEqual(select([]),[]);
assert.deepEqual(select(['Google']),['Google']);
console.log('Company comparisons: multiple selections, unavailable sources and empty/saved selection preserved.');
