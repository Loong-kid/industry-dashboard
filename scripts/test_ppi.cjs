const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const source = fs.readFileSync('assets/ppi.js', 'utf8');
  const classificationUrl = 'data:text/javascript;base64,' + Buffer.from(fs.readFileSync('assets/ppi-classification.js', 'utf8')).toString('base64');
  const classes = await import(classificationUrl);
  const ppi = await import('data:text/javascript;base64,' + Buffer.from(source.replace('./ppi-classification.js', classificationUrl)).toString('base64'));
  assert.equal(ppi.shiftMonth('2026-01', -1), '2025-12');
  assert.equal(ppi.shiftMonth('2026-01', -12), '2025-01');
  const points = [['2025-01', 100], ['2025-12', 150], ['2026-01', 200]];
  const stats = ppi.stats(points);
  assert.equal(stats.yoy, 100);
  assert(Math.abs(stats.mom - 100 / 3) < 1e-9);
  assert.equal(ppi.stats([['2025-01', 100], ['2025-11', 150], ['2026-01', 200]]).mom, null);
  assert.equal(ppi.stats(points, '2026-02').latest, null);
  assert.equal(ppi.change(50, 0), null);
  const accelerated = [['2024-12', 100], ['2025-01', 100], ['2025-12', 102], ['2026-01', 105]];
  assert(Math.abs(ppi.yoyAcceleration(accelerated, '2026-01') - 3) < 1e-9);
  assert.equal(ppi.yoyAcceleration(points, '2026-01'), null);
  assert.deepEqual(ppi.transform(points, 'YoY %').at(-1), ['2026-01', 100]);
  assert.deepEqual(ppi.transform(points, 'Indexed (=100)', '1Y', '2026-12'), [['2025-12', 100], ['2026-01', 200 / 150 * 100]]);
  assert(ppi.matches({id: 'PCU123', title: 'Steel mill products'}, 'steel mill'));
  assert(!ppi.matches({id: 'PCU123', title: 'Steel products'}, 'steel mill'));
  assert(ppi.csvText(['Title', 'Value'], [['a,"b', null]]).startsWith('\uFEFF"Title","Value"\r\n"a,""b",""'));
  const aligned = ppi.indexedComparison([{id: 'one', points}, {id: 'two', points: [['2025-02', 80], ['2025-12', 100], ['2026-01', 150]]}], 'MAX', '2026-01');
  assert.equal(aligned.baseDate, '2025-12');
  assert(aligned.points.every(d => d.points[0][1] === 100));
  assert.equal(ppi.indexedComparison([{id:'one',points:[['2020-01',100]]},{id:'two',points:[['2026-01',100]]}], 'MAX', '2026-01').baseDate, null);
  assert.deepEqual(classes.parseIndustry('PCU3344133344131'), {code:'334413',suffix:'1'});
  assert.deepEqual(classes.parseIndustry('PCU33441K33441KP'), {code:'33441K',suffix:'P'});
  assert.equal(classes.lifecycle('2026-08','2026-08'), 'current');
  assert.equal(classes.lifecycle('2026-05','2026-08'), 'lagged');
  assert.equal(classes.lifecycle('2022-12','2026-08'), 'historical');
  const manifest = JSON.parse(fs.readFileSync('data/ppi/catalog.json', 'utf8'));
  const navigation = JSON.parse(fs.readFileSync('data/ppi/navigation.json', 'utf8'));
  assert.equal(navigation.updated, manifest.updated);
  const records = manifest.series.map(classes.classify);
  assert(records.every(s => !s.unknown && classes.GROUPS.some(g => g.id === s.group)));
  const reps = classes.representatives(records, navigation.latest_dates, manifest.data_through);
  assert(reps.length >= 60 && reps.length <= 80, `representatives: ${reps.length}`);
  assert(reps.every(s => s.kind === 'industry' && navigation.latest_dates[s.id] === manifest.data_through));
  assert.equal(new Set(reps.map(s => s.group)).size, 12);
  const semiconductor = records.find(s => s.id === 'PCU334413334413');
  const transformer = records.find(s => s.id === 'PCU335311335311');
  assert(semiconductor.themes.includes('semiconductor'));
  assert(transformer.themes.includes('power') && transformer.themes.includes('datacenter'));
  assert.equal(records.find(s => s.id === 'PCU335911335911P').kind, 'primary');
  const tree = classes.buildTree(records);
  assert.equal(tree.roots.reduce((sum, node) => sum + node.count, 0), records.length);
  const componentNode = tree.nodes.get('3344');
  assert(componentNode.children.some(node => node.code === '33441'));
  const sorted = classes.rankIndustries([{s: semiconductor,yoy:5},{s:records.find(s=>s.id==='PCU334334'),yoy:4},{s:records.find(s=>s.id==='PCU334413334413P'),yoy:100}], 'yoy');
  assert.equal(sorted.length, 1);
  assert.equal(sorted[0].s.id, semiconductor.id);
  const catalog = JSON.parse(fs.readFileSync('data/catalog.json', 'utf8'));
  assert.equal(catalog.industries.filter(i => i.id === 'ppi').length, 1);
  console.log(`PASS: calendar growth, acceleration, common-base comparison, CSV, 12 groups, ${reps.length} current representatives, themes, full hierarchy and ranking deduplication`);
})().catch(e => { console.error(e); process.exitCode = 1; });
