const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const source=fs.readFileSync('assets/ai-overview.js','utf8');
  const {selectRows,valueOf,csvText,safeURL,escapeHTML,publicModelTable}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
  const llm=JSON.parse(fs.readFileSync('data/datacenter/dc_ai_overview.json')).tables[0];
  assert.equal(selectRows(llm).length,110);
  const anthropic=selectRows(llm,{provider:'Anthropic',search:' CLAUDE '});
  assert(anthropic.length>1);assert(anthropic.every(r=>r.provider==='Anthropic'));
  assert.equal(selectRows(llm,{search:'no-model-matches-this'}).length,0);
  const synthetic={provider_key:'A',rows:[{provider:'test',cells:{J:{text:'10%',number:.1}}},{provider:'test',cells:{J:{text:'2%',number:.02}}},{provider:'test',cells:{}}]};
  assert.deepEqual(selectRows(synthetic,{sort:'J'}).map(r=>valueOf(r,'J',synthetic)),['2%','10%','']);
  assert.deepEqual(selectRows(synthetic,{sort:'J',direction:-1}).map(r=>valueOf(r,'J',synthetic)),['10%','2%','']);
  const video=JSON.parse(fs.readFileSync('data/datacenter/dc_ai_overview2.json')).tables[1];
  const row=video.rows.find(r=>r.model==='Gen-4.5');assert.equal(valueOf(row,'P',video),'0');
  assert(csvText(video,[row],video.columns).includes('"0"'));
  assert.equal(safeURL('javascript:alert(1)'), '');assert.equal(safeURL('https://example.com'),'https://example.com');
  assert.equal(escapeHTML('<script>"&'), '&lt;script&gt;&quot;&amp;');
  assert(csvText(synthetic,[{provider:'=malicious',cells:{}}],[{key:'A',label:'Company'}]).includes('"\'=malicious"'));
  const catalog=JSON.parse(fs.readFileSync('data/catalog.json'));
  const dc=catalog.industries.find(i=>i.id==='datacenter');
  assert(dc.tabs.some(t=>t.id==='ai_overview'));
  assert(!dc.tabs.some(t=>t.id==='ai_overview2'));
  assert.deepEqual(dc.sections.filter(s=>s.tab==='ai_overview').flatMap(s=>s.indicators),['dc_ai_model_benchmarks','dc_ai_overview','dc_ai_overview2']);
  const recent=JSON.parse(fs.readFileSync('data/datacenter/dc_ai_model_benchmarks.json'));
  const comparison=publicModelTable(recent);
  assert.equal(new Set(comparison.rows.map(row=>row.id)).size,comparison.rows.length);
  assert.equal(comparison.rows[0].id,'gemini-4-neon');
  const sol=selectRows(comparison,{provider:'OpenAI',search:'6.2 sol'})[0];
  assert.deepEqual(['input','cache','output','score','effort','cost'].map(key=>sol.cells[key].number ?? sol.cells[key].text),[2,.1,10,55,'high',.56]);
  assert.match(sol.cells.score.note,/max 57점/);
  const decision=comparison.rows.find(row=>row.id==='microsoft-decision-1.1');
  assert.equal(valueOf(decision,'output',comparison),'$0.00');
  assert.equal(valueOf(decision,'score',comparison),'');
  assert.equal(selectRows(comparison,{sort:'score',direction:-1}).at(-1).id,decision.id);
  for(const row of recent.models) {
    assert(row.release<=recent.imported);
    assert(safeURL(row.release_url)&&safeURL(row.price.url));
    assert(row.benchmark===null||safeURL(row.benchmark.url));
  }
  console.log('AI overview: search, numeric sort, blanks, zero, CSV and safe display passed');
})().catch(err=>{console.error(err);process.exit(1)});
